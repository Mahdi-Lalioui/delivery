export type FeedMessages = typeof en;

export function getFeedMessages(locale: Locale): FeedMessages {
  return messages[locale];
}

export function getFeedCuisineLabel(locale: Locale, cuisine: string) {
  const { cuisines, otherCuisine } = getFeedMessages(locale);
  return Object.entries(cuisines).find(([code]) => code === cuisine)?.[1] ?? otherCuisine;
}

/** Replaces `{key}` placeholders in a feed message. */
export function fillFeedMessage(template: string, values: Record<string, string>) {
  return template.replace(/\{(\w+)\}/gu, (match, key: string) => values[key] ?? match);
}
